/* Общие помощники системных вызовов ВМ: ввод текста. Только stdint, без libc. */
#ifndef PTVMIO_H
#define PTVMIO_H

#include "vm.h"

/* Номера системных вызовов (команда sys n). У ПК (host.c) и ядра они одинаковые. */
#define VM_SYS_PUTC     1   /* ( c -- )     вывести байт */
#define VM_SYS_GETC     2   /* ( -- c )     прочитать байт без ожидания, -1 если нет */
#define VM_SYS_READLINE 3   /* ( -- строка) прочитать строку с консоли, ждать Enter */
#define VM_SYS_TIME     4   /* ( -- мс )    миллисекунды с запуска (по кругу примерно через 49 суток) */
#define VM_SYS_SLEEP    5   /* ( мс -- )    подождать столько миллисекунд */

/* Превращает байты UTF-8 в строку Слога (блок [длина][коды символов]) в куче программы
   и кладёт её адрес на стек. Некорректные байты становятся символом U+FFFD.
   Возвращает 0 или код ошибки ВМ (VM_ERR_MEM, если не хватает памяти). */
int vm_push_utf8(vm_t *vm, const uint8_t *s, uint32_t n);

#endif