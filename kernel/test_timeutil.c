/* Проверки арифметики времени ядра. Печатает "TIMEUTIL TESTS PASS". */
#include <stdio.h>
#include "timeutil.h"

static int fails;

static void check(const char *name, uint32_t got, uint32_t exp) {
    if (got != exp) { fails++; printf("FAIL %s got %u exp %u\n", name, got, exp); }
}

int main(void) {
    /* 10 МГц: 10000 единиц в миллисекунде, такт 100 мс */
    check("ноль", time_ms(0, 100, 10000, 0, 0), 0);
    check("доля такта", time_ms(0, 100, 10000, 25000, 0), 2);
    check("такты", time_ms(10, 100, 10000, 5000, 5000), 1000);
    check("такты и доля", time_ms(10, 100, 10000, 125000, 100000), 1002);
    check("без полной миллисекунды", time_ms(3, 100, 10000, 9999, 0), 300);
    check("ровно миллисекунда", time_ms(3, 100, 10000, 10000, 0), 301);
    /* счётчик времени перешёл через 2^32 между срабатыванием и чтением */
    check("переход счётчика", time_ms(7, 100, 10000, 20000, 0xFFFFFF00u), 700 + (20000u + 0x100u) / 10000u);
    /* миллисекунды переходят через 2^32 (около 49,7 суток): разности остаются верными */
    uint32_t a = time_ms(42949672, 100, 10000, 0, 0);       /* 4294967200 мс */
    uint32_t b = time_ms(42949673, 100, 10000, 0, 0);       /* на 100 мс позже, с переходом */
    check("разность через переход", b - a, 100);
    check("значение после перехода", b, 4294967300u - 4294967296u);
    /* малые такты (как в симуляторе): время просто не растёт, но не ломается */
    check("нулевой такт", time_ms(500, 0, 10000, 3000, 0), 0);
    if (fails == 0) puts("TIMEUTIL TESTS PASS");
    else printf("TIMEUTIL TESTS FAIL: %d\n", fails);
    return fails != 0;
}