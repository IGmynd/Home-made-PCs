#!/usr/bin/env python3
"""Тесты строк «Слога»: значения, склейка, сравнение, преобразования, вывод типов.
Запуск: test_slog3.py путь/к/host"""
import os
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ptasm  # noqa: E402
import slog   # noqa: E402

HOST = sys.argv[1]
fails = 0


def run(src):
    img = ptasm.assemble(slog.compile_source(src))
    with tempfile.NamedTemporaryFile(suffix=".ptb", delete=False) as f:
        f.write(img)
        path = f.name
    try:
        r = subprocess.run([HOST, path], capture_output=True, timeout=20)
    finally:
        os.unlink(path)
    return r.returncode, r.stdout.decode("utf-8"), r.stderr.decode("utf-8")


def ok(name, src, expected):
    global fails
    try:
        code, out, err = run(src)
    except Exception as e:  # noqa: BLE001
        fails += 1
        print(f"FAIL {name}: исключение {e}")
        return
    if code != 0 or out != expected:
        fails += 1
        print(f"FAIL {name}: код={code} вывод={out!r} ожидалось={expected!r} {err.strip()}")


def bad(name, src, fragment):
    global fails
    try:
        slog.compile_source(src)
    except slog.SlogError as e:
        if fragment not in str(e):
            fails += 1
            print(f"FAIL {name}: ошибка {e!s} не содержит {fragment!r}")
        return
    fails += 1
    print(f"FAIL {name}: ошибки не было, а ждали {fragment!r}")


def runtime_fail(name, src, fragment):
    global fails
    code, out, err = run(src)
    if code == 0 or fragment not in err:
        fails += 1
        print(f"FAIL {name}: код={code} stderr={err!r} ждали {fragment!r}")


# ---------------- значения и вывод
ok("строка в переменной", 'с = "привет"\nпечать(с)\n', "привет\n")
ok("длина в символах", 'печать(длина("привет"), длина("abc"), длина(""))\n', "6 3 0\n")
ok("код символа", 'печать("абв"[1], "abc"[0])\n', "1073 97\n")
ok("склейка", 'печать("а" + "б" + "в")\n', "абв\n")
ok("составная склейка", 'с = "а"\nс += "б"\nс += "в"\nпечать(с)\n', "абв\n")
ok("пустая строка", 'печать("", длина(""))\n', " 0\n")
ok("экранирование в строках", 'печать("а\\тб\\нв")\n', "а\tб\nв\n")
ok("несколько строк в печати", 'печать("а", "б", 1, "в")\n', "а б 1 в\n")

# ---------------- сравнение
ok("равенство", 'печать("а" == "а", "а" == "б", "аб" == "а", "" == "")\n', "1 0 0 1\n")
ok("равенство: один префикс", 'печать("а" == "аб", "аб" == "а", "аб" == "аб", "аб" == "ав")\n', "0 0 1 0\n")
ok("неравенство", 'печать("а" != "б", "а" != "а")\n', "1 0\n")
ok("сравнение переменных", 'а = "мир"\nб = "ми" + "р"\nпечать(а == б)\n', "1\n")
ok("условие по строкам", 'с = "да"\nесли с == "да":\n    печать(1)\nиначе:\n    печать(2)\n', "1\n")

# ---------------- преобразования
ok("строка из числа", "печать(строка(0), строка(7), строка(-12), строка(2147483647))\n", "0 7 -12 2147483647\n")
ok("число из строки", 'печать(число("42"), число("-5х"), число(""), число("абв"), число("0"))\n', "42 -5 0 0 0\n")
ok("туда и обратно", 'печать(число(строка(123456)) + 1)\n', "123457\n")
ok("текст с числом", 'печать("итого: " + строка(25) + " шт.")\n', "итого: 25 шт.\n")
ok("срез", 'печать(срез("привет", 2, 4), срез("привет", 0, 3))\n', "ив при\n")
ok("срез с подрезкой", 'печать(срез("abc", -5, 2), срез("abc", 1, 99), срез("abc", 5, 9), срез("abc", 2, 1))\n', "ab bc  \n")
ok("из кода", 'печать(из_кода(1103) + из_кода(33))\n', "я!\n")

# ---------------- UTF-8: 1, 2, 3 и 4 байта
ok("utf8 1 байт", "печать(из_кода(65))\n", "A\n")
ok("utf8 2 байта", "печать(из_кода(1103))\n", "я\n")
ok("utf8 3 байта", "печать(из_кода(8364))\n", "€\n")
ok("utf8 4 байта", "печать(из_кода(128512))\n", "😀\n")
ok("utf8 в литерале", 'печать("€ 😀 ё")\n', "€ 😀 ё\n")

# ---------------- строки и функции, вывод типов
ok("параметр и результат", """
функция привет(имя):
    вернуть "Привет, " + имя + "!"
печать(привет("мир"))
""", "Привет, мир!\n")
ok("обратить строку", """
функция обратить(с):
    р = ""
    для к в диапазон(длина(с)):
        р = из_кода(с[к]) + р
    вернуть р
печать(обратить("привет"))
печать(обратить("шалаш") == "шалаш", обратить("слог") == "слог")
""", "тевирп\n1 0\n")
ok("функция до определения", """
печать(приветствие())
функция приветствие():
    вернуть "добрый день"
""", "добрый день\n")
ok("результат функции в переменной", """
функция имя():
    вернуть "ПТ"
х = имя()
печать("система " + х)
""", "система ПТ\n")
ok("глобальная строка", """
сообщение = "а"
функция добавить():
    глобальная сообщение
    сообщение += "б"
добавить()
добавить()
печать(сообщение)
""", "абб\n")
ok("рекурсия со строкой", """
функция повтор(с, н):
    если н == 0:
        вернуть ""
    вернуть с + повтор(с, н - 1)
печать(повтор("аб", 3))
""", "абабаб\n")
ok("цепочка вызовов", """
функция а1(с):
    вернуть б1(с)
функция б1(с):
    вернуть с + "!"
печать(а1("ура"))
""", "ура!\n")

# ---------------- строки и списки
ok("обход строки", 'для х в "аб":\n    печать(х)\n', "1072\n1073\n")
ok("список строк с указанием типа", """
слова = ["один", "два", "три"]
для с в слова:
    печать(строкой(с))
печать(длина(слова[0]), строкой(слова[1]))
""", "один\nдва\nтри\n4 два\n")
ok("строка в списке изменяется", """
с = "абв"
с[1] = 1100
печать(с)
""", "аьв\n")

# ---------------- имена встроенных функций можно занимать
ok("переменная число", "число = 5\nпечать(число)\n", "5\n")
ok("переменная строка", 'строка = "а"\nпечать(строка)\n', "а\n")
ok("своя функция вместо встроенной", "функция срез(а, б):\n    вернуть а + б\nпечать(срез(2, 3))\n", "5\n")

# ---------------- ошибки типов при компиляции
bad("строка плюс число", 'печать("а" + 1)\n', "нельзя сложить строку и число")
bad("число плюс строка", 'печать(1 + "а")\n', "нельзя сложить строку и число")
bad("вычитание строк", 'печать("а" - "б")\n', "к строкам не применима")
bad("строка равна числу", 'печать("а" == 1)\n', "нельзя сравнивать строку с числом")
bad("разные типы в переменной", 'х = 1\nх = "а"\n', "и число, и строку")
bad("разные типы через присваивание вызова", 'функция ф():\n    вернуть "а"\nх = 1\nх = ф()\n', "и число, и строку")
bad("разные типы параметра", 'функция ф(а):\n    вернуть а\nф(1)\nф("а")\n', "параметр «а» функции «ф»")
bad("разные типы результата", 'функция ф(н):\n    если н:\n        вернуть 1\n    вернуть "а"\n', "результат функции")
bad("строка в условии", 'если "а":\n    пропуск\n', "условие: ожидалось число")
bad("строка в пока", 'пока "а":\n    пропуск\n', "условие: ожидалось число")
bad("число() от числа", "печать(число(5))\n", "ожидалась строка")
bad("строка() от строки", 'печать(строка("а"))\n', "ожидалось число")
bad("срез от числа", "печать(срез(5, 0, 1))\n", "ожидалась строка")
bad("срез со строкой в границе", 'печать(срез("а", "б", 1))\n', "ожидалось число")
bad("минус строки", 'печать(-"а")\n', "унарная операция")
bad("индекс строкой", 'печать("а"["б"])\n', "индекс: ожидалось число")
bad("не от строки", 'печать(не "а")\n', "ожидалось число")
bad("число() от элемента списка", 'с = ["а"]\nпечать(число(с[0]))\n', "строкой(")
bad("диапазон со строкой", 'для к в диапазон("а"):\n    пропуск\n', "ожидалось число")

# ---------------- ошибки выполнения
runtime_fail("индекс строки вне границ", 'печать("абв"[5])\n', "vm error -13")
runtime_fail("отрицательный индекс строки", 'печать("абв"[-1])\n', "vm error -13")

if fails == 0:
    print("SLOG3 TESTS PASS")
else:
    print(f"SLOG3 TESTS FAIL: {fails}")
sys.exit(1 if fails else 0)