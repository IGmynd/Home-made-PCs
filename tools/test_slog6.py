#!/usr/bin/env python3
"""Тесты «Слога»: метки памяти, присваивание нескольких значений, сравнение строк, библиотека matem.
Запуск: test_slog6.py путь/к/host"""
import os
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ptasm  # noqa: E402
import slog   # noqa: E402

HOST = sys.argv[1]
fails = 0


def run(src, stdin=b""):
    img = ptasm.assemble(slog.compile_source(src))
    with tempfile.NamedTemporaryFile(suffix=".ptb", delete=False) as f:
        f.write(img)
        path = f.name
    try:
        r = subprocess.run([HOST, path], input=stdin, capture_output=True, timeout=20)
    finally:
        os.unlink(path)
    return r.returncode, r.stdout.decode("utf-8"), r.stderr.decode("utf-8")


def ok(name, src, stdin, expected):
    global fails
    try:
        code, out, err = run(src, stdin)
    except Exception as e:  # noqa: BLE001
        fails += 1
        print(f"FAIL {name}: исключение {e}")
        return
    if code != 0 or out != expected:
        fails += 1
        print(f"FAIL {name}: код={code} вывод={out!r} ожидалось={expected!r} {err.strip()}")


def bad(name, src, fragment):
    global fails
    try:
        slog.compile_source(src)
    except slog.SlogError as e:
        if fragment not in str(e):
            fails += 1
            print(f"FAIL {name}: ошибка {e!s} не содержит {fragment!r}")
        return
    fails += 1
    print(f"FAIL {name}: ошибки не было, а ждали {fragment!r}")


def runtime_fail(name, src, fragment):
    global fails
    code, out, err = run(src)
    if code == 0 or fragment not in err:
        fails += 1
        print(f"FAIL {name}: код={code} stderr={err!r} ждали {fragment!r}")


# ================= метки памяти
ok("метка и сброс", """
м = память_метка()
а = список(10)
б = память_метка()
память_сбросить(м)
в = память_метка()
печать(м == в, б > м)
""", b"", "1 1\n")
ok("после сброса память переиспользуется", """
м = память_метка()
а = выделить(8)
память_сбросить(м)
б = выделить(8)
печать(а == б)
""", b"", "1\n")
ok("результат вычисляется до сброса", """
м = память_метка()
с = "абв" + "где"
н = длина(с)
память_сбросить(м)
печать(н)
""", b"", "6\n")
ok("цикл со сбросом не расходует память", """
для к в диапазон(3000):
    м = память_метка()
    с = строка(к) + " итерация номер " + строка(к * 2)
    память_сбросить(м)
печать("готово")
""", b"", "готово\n")
ok("вложенные метки", """
внешняя = память_метка()
а = выделить(8)
внутренняя = память_метка()
б = выделить(8)
память_сбросить(внутренняя)
в = выделить(8)
печать(б == в, а < б)
память_сбросить(внешняя)
г = выделить(8)
печать(г == а)
""", b"", "1 1\n1\n")
ok("метка в функции", """
функция работа(н):
    м = память_метка()
    с = строка(н) + "!"
    итог = длина(с)
    память_сбросить(м)
    вернуть итог
печать(работа(12345), работа(7))
""", b"", "6 2\n")
bad("метка с аргументом", "печать(память_метка(1))\n", "принимает аргументов")
bad("сброс без аргумента", "память_сбросить()\n", "принимает аргументов")
bad("сброс со строкой", 'память_сбросить("а")\n', "ожидалось число")

# ================= ошибки выполнения
runtime_fail("цикл без сброса исчерпывает память", """
для к в диапазон(3000):
    с = строка(к) + " итерация номер " + строка(к * 2)
печать("готово")
""", "vm error -6")
runtime_fail("сброс за границу", "память_сбросить(99999999)\n", "vm error -6")
runtime_fail("сброс в отрицательное", "н = 0 - 4\nпамять_сбросить(н)\n", "vm error -6")
runtime_fail("сброс по невыровненной метке", "а = выделить(8)\nпамять_сбросить(2)\n", "vm error -6")

# ================= несколько значений сразу
ok("обмен", "а = 1\nб = 2\nа, б = б, а\nпечать(а, б)\n", b"", "2 1\n")
ok("три значения", "а, б, в = 1, 2, 3\nа, б, в = б, в, а\nпечать(а, б, в)\n", b"", "2 3 1\n")
ok("правая часть считается до присваивания", "х, у = 3, 4\nх, у = у, х + у\nпечать(х, у)\n", b"", "4 7\n")
ok("элементы списка", "а = [1, 2, 3]\nа[0], а[2] = а[2], а[0]\nпечать(а[0], а[1], а[2])\n", b"", "3 2 1\n")
ok("числа Фибоначчи", "а, б = 0, 1\nдля к в диапазон(10):\n    а, б = б, а + б\nпечать(а)\n", b"", "55\n")
ok("строки", 'п, в = "а", "б"\nп, в = в, п\nпечать(п + в)\n', b"", "ба\n")
ok("в функции", """
функция поменять(а, б):
    а, б = б, а
    вернуть а * 10 + б
печать(поменять(1, 2))
""", b"", "21\n")
ok("в сортировке", """
д = [4, 2, 9, 1]
для к в диапазон(длина(д)):
    для п в диапазон(длина(д) - 1 - к):
        если д[п] > д[п + 1]:
            д[п], д[п + 1] = д[п + 1], д[п]
печать(д[0], д[1], д[2], д[3])
""", b"", "1 2 4 9\n")
ok("смешанные типы в одной строке", 'число, текст = 5, "пять"\nпечать(число, текст)\n', b"", "5 пять\n")
bad("разное число частей", "а, б = 1\n", "слева 2 имён")
bad("разное число частей наоборот", "а = 1\nа, б = 1, 2, 3\n", "слева 2 имён")
bad("слева не имя", "1, а = 2, 3\n", "слева допустимы")
bad("слева вызов", "ф(), а = 2, 3\n", "слева допустимы")
bad("нет равно", "а, б\n", "«=»")
bad("тип по частям", 'х, у = 1, "а"\nх = "б"\n', "и число, и строку")

# ================= сравнение строк по алфавиту
ok("порядок строк", 'печать("а" < "б", "б" < "а", "а" < "а", "а" <= "а", "аб" > "а", "а" > "аб", "ба" >= "аб", "" < "а")\n',
   b"", "1 0 0 1 1 0 1 1\n")
ok("порядок по кодам символов", 'печать("Я" < "а", "ё" > "я", "Z" < "a", "10" < "9")\n', b"", "1 1 1 1\n")
ok("порядок равных", 'печать("" < "", "" <= "", "" >= "", "абв" <= "абв")\n', b"", "0 1 1 1\n")
ok("сортировка строк", """
с = ["яблоко", "арбуз", "груша", "банан"]
для к в диапазон(1, длина(с)):
    значение = строкой(с[к])
    п = к - 1
    пока п >= 0 и строкой(с[п]) > значение:
        с[п + 1] = с[п]
        п -= 1
    с[п + 1] = значение
для х в с:
    печать(строкой(х))
""", b"", "арбуз\nбанан\nгруша\nяблоко\n")
bad("строка и число по порядку", 'печать("а" < 1)\n', "нельзя сравнивать строку с числом")
bad("умножение строк по-прежнему нельзя", 'печать("а" * "б")\n', "к строкам не применима")

# ================= математика
M = 'подключить "matem"\n'
ok("абс", M + "печать(абс(-5), абс(5), абс(0))\n", b"", "5 5 0\n")
ok("мин и макс", M + "печать(мин(3, 7), макс(3, 7), мин(-1, -5), макс(2, 2))\n", b"", "3 7 -5 2\n")
ok("знак", M + "печать(знак(-9), знак(0), знак(12))\n", b"", "-1 0 1\n")
ok("степень", M + "печать(степень(2, 10), степень(3, 0), степень(-2, 3), степень(5, 1), степень(2, -1))\n", b"", "1024 1 -8 5 0\n")
ok("нод", M + "печать(нод(12, 18), нод(17, 5), нод(0, 7), нод(-12, 18), нод(100, 75))\n", b"", "6 1 7 6 25\n")
ok("корень", M + "печать(корень(0), корень(1), корень(15), корень(16), корень(17), корень(2147483647), корень(-4))\n", b"", "0 1 3 4 4 46340 0\n")
ok("по_модулю", M + "печать(по_модулю(7, 3), по_модулю(-7, 3), по_модулю(-1, 5), по_модулю(0, 4))\n", b"", "1 2 4 0\n")
ok("ограничить", M + "печать(ограничить(5, 1, 10), ограничить(-3, 1, 10), ограничить(99, 1, 10))\n", b"", "5 1 10\n")
ok("корень точный на квадратах", M + """
верно = истина
для к в диапазон(1, 200):
    если корень(к * к) != к или корень(к * к + 1) != к или корень(к * к - 1) != к - 1:
        верно = ложь
печать(верно)
""", b"", "1\n")

if fails == 0:
    print("SLOG6 TESTS PASS")
else:
    print(f"SLOG6 TESTS FAIL: {fails}")
sys.exit(1 if fails else 0)
