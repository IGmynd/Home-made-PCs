#!/usr/bin/env python3
"""Тесты возможностей «Слога» второй очереди: списки, цикл «для», числа 0ш и 0д, куча.
Запуск: test_slog2.py путь/к/host"""
import os
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ptasm  # noqa: E402
import slog   # noqa: E402

HOST = sys.argv[1]
fails = 0


def run(src):
    img = ptasm.assemble(slog.compile_source(src))
    with tempfile.NamedTemporaryFile(suffix=".ptb", delete=False) as f:
        f.write(img)
        path = f.name
    try:
        r = subprocess.run([HOST, path], capture_output=True, timeout=20)
    finally:
        os.unlink(path)
    return r.returncode, r.stdout.decode("utf-8"), r.stderr.decode("utf-8")


def ok(name, src, expected):
    global fails
    try:
        code, out, err = run(src)
    except Exception as e:  # noqa: BLE001
        fails += 1
        print(f"FAIL {name}: исключение {e}")
        return
    if code != 0 or out != expected:
        fails += 1
        print(f"FAIL {name}: код={code} вывод={out!r} ожидалось={expected!r} {err.strip()}")


def bad(name, src, fragment):
    global fails
    try:
        slog.compile_source(src)
    except slog.SlogError as e:
        if fragment not in str(e):
            fails += 1
            print(f"FAIL {name}: ошибка {e!s} не содержит {fragment!r}")
        return
    fails += 1
    print(f"FAIL {name}: ошибки не было, а ждали {fragment!r}")


def runtime_fail(name, src, fragment):
    global fails
    code, out, err = run(src)
    if code == 0 or fragment not in err:
        fails += 1
        print(f"FAIL {name}: код={code} stderr={err!r} ждали {fragment!r}")


# ---------------- списки
ok("список", "а = [10, 20, 30]\nпечать(а[0], а[1], а[2], длина(а))\n", "10 20 30 3\n")
ok("запись в элемент", """
а = [1, 2, 3]
а[1] = 50
а[2] += 7
а[0] *= 9
печать(а[0], а[1], а[2])
""", "9 50 10\n")
ok("список(n)", "а = список(5)\nпечать(длина(а), а[0], а[4])\n", "5 0 0\n")
ok("пустой список", "а = []\nпечать(длина(а))\n", "0\n")
ok("вложенные списки", """
м = [[1, 2], [3, 4]]
м[0][1] = 9
печать(м[0][1], м[1][0], длина(м), длина(м[1]))
""", "9 3 2 2\n")
ok("выражение в индексе", "а = [5, 6, 7]\nк = 1\nпечать(а[к + 1], а[к * 0])\n", "7 5\n")
ok("список в функцию", """
функция заполнить(с, н):
    для к в диапазон(длина(с)):
        с[к] = н
данные = список(3)
заполнить(данные, 7)
печать(данные[0], данные[1], данные[2])
""", "7 7 7\n")
ok("список локально в функции", """
функция сумма(н):
    а = список(н)
    для к в диапазон(н):
        а[к] = к * к
    итог = 0
    для х в а:
        итог += х
    вернуть итог
печать(сумма(5), сумма(10))
""", "30 285\n")
ok("выделить и память", """
а = выделить(8)
б = выделить(4)
писать(а, 11)
писать(б, 22)
печать(читать(а), читать(б), б - а)
""", "11 22 8\n")

# ---------------- цикл для
ok("диапазон(n)", "сумма = 0\nдля к в диапазон(5):\n    сумма += к\nпечать(сумма)\n", "10\n")
ok("диапазон с шагом", "для к в диапазон(2, 11, 3):\n    печать(к)\n", "2\n5\n8\n")
ok("диапазон вниз", "для к в диапазон(5, 0, -2):\n    печать(к)\n", "5\n3\n1\n")
ok("пустой диапазон", "для к в диапазон(3, 3):\n    печать(1)\nпечать(0)\n", "0\n")
ok("прервать и продолжить в для", """
для к в диапазон(10):
    если к == 2:
        продолжить
    если к == 5:
        прервать
    печать(к)
""", "0\n1\n3\n4\n")
ok("переменная цикла не влияет", "для к в диапазон(3):\n    печать(к)\n    к = 100\n", "0\n1\n2\n")
ok("для по списку", "сумма = 0\nдля х в [4, 5, 6]:\n    сумма += х\nпечать(сумма)\n", "15\n")
ok("для внутри функции", """
функция сумма_до(н):
    итог = 0
    для к в диапазон(1, н + 1):
        итог += к
    вернуть итог
печать(сумма_до(10), сумма_до(100))
""", "55 5050\n")
ok("вложенные циклы", """
счёт = 0
для а в диапазон(3):
    для б в диапазон(4):
        счёт += 1
печать(счёт)
""", "12\n")
ok("два цикла подряд", """
для к в диапазон(2):
    печать(к)
для к в диапазон(2):
    печать(к + 10)
""", "0\n1\n10\n11\n")
ok("в как имя переменной", "в = 5\nпечать(в)\n", "5\n")

# ---------------- числа
ok("шестнадцатеричные и двоичные", "печать(0шЕЕ, 0д1010, 0ш10, 0шЕЕЕЕЕЕЕЕ, 0ш7ЕЕЕЕЕЕЕ)\n",
   "255 10 16 -1 2147483647\n")
ok("строчные цифры", "печать(0шее, 0шаБ)\n", "255 171\n")

# ---------------- программы целиком
ok("пузырьковая сортировка", """
данные = [5, 3, 9, 1, 7, 8, 2]
размер = длина(данные)
для проход в диапазон(0, размер - 1):
    для к в диапазон(0, размер - 1 - проход):
        если данные[к] > данные[к + 1]:
            врем = данные[к]
            данные[к] = данные[к + 1]
            данные[к + 1] = врем
для х в данные:
    печать(х)
""", "1\n2\n3\n5\n7\n8\n9\n")
ok("решето Эратосфена", """
граница = 100
решето = список(граница + 1)
найдено = 0
для ч в диапазон(2, граница + 1):
    если решето[ч] == 0:
        найдено += 1
        к = ч * ч
        пока к <= граница:
            решето[к] = 1
            к += ч
печать(найдено)
""", "25\n")

# ---------------- ошибки компиляции
bad("диапазон 4 аргумента", "для к в диапазон(1, 2, 3, 4):\n    пропуск\n", "от 1 до 3")
bad("шаг не константа", "н = 2\nдля к в диапазон(0, 10, н):\n    пропуск\n", "числом-константой")
bad("шаг ноль", "для к в диапазон(0, 10, 0):\n    пропуск\n", "нулём")
bad("диапазон вне цикла", "х = диапазон(3)\n", "только в цикле")
bad("присваивание вызову", "длина(1) = 3\n", "слева от")
bad("присваивание списку", "[1, 2] = 3\n", "слева от")
bad("имя цикла", "для 5 в диапазон(3):\n    пропуск\n", "имя переменной цикла")
bad("нет двоеточия", "для к в [1, 2]\n    пропуск\n", "ожидалось")
bad("нет в", "для к [1, 2]:\n    пропуск\n", "«в»")
bad("двоичное с двойкой", "х = 0д12\n", "недопустимая цифра")
bad("пустое шестнадцатеричное", "х = 0ш\n", "должны идти цифры")
bad("латинская цифра в 0ш", "х = 0шff\n", "недопустимая цифра")
bad("слишком длинное 0ш", "х = 0шЕЕЕЕЕЕЕЕЕ\n", "32 бита")
bad("свободная_память убрана", "х = свободная_память()\n", "не определена")
bad("список арность", "х = список(1, 2)\n", "принимает аргументов")
bad("не закрыта скобка списка", "х = [1, 2\n", "скобка")

# ---------------- ошибки выполнения: ВМ останавливает программу, а не падает
runtime_fail("индекс вне списка", "а = [1, 2]\nпечать(а[2])\n", "vm error -13")
runtime_fail("отрицательный индекс", "а = [1, 2]\nпечать(а[-1])\n", "vm error -13")
runtime_fail("запись вне списка", "а = [1, 2]\nа[5] = 1\n", "vm error -13")
runtime_fail("список отрицательной длины", "н = 0 - 1\nа = список(н)\n", "vm error -13")
runtime_fail("список слишком большой", "а = список(100000)\n", "vm error -6")
runtime_fail("выделить слишком много", "а = выделить(1000000)\n", "vm error -6")

if fails == 0:
    print("SLOG2 TESTS PASS")
else:
    print(f"SLOG2 TESTS FAIL: {fails}")
sys.exit(1 if fails else 0)