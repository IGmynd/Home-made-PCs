#!/usr/bin/env python3
"""Тесты модулей и библиотеки «Слога»: подключить, выбрасывание лишних функций, stroki и spiski.
Запуск: test_slog5.py путь/к/host"""
import os
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ptasm  # noqa: E402
import slog   # noqa: E402

HOST = sys.argv[1]
fails = 0


def run(src, base_dir=None, lib_dirs=None):
    img = ptasm.assemble(slog.compile_source(src, base_dir, lib_dirs))
    with tempfile.NamedTemporaryFile(suffix=".ptb", delete=False) as f:
        f.write(img)
        path = f.name
    try:
        r = subprocess.run([HOST, path], capture_output=True, timeout=30)
    finally:
        os.unlink(path)
    return r.returncode, r.stdout.decode("utf-8"), r.stderr.decode("utf-8")


def ok(name, src, expected, base_dir=None, lib_dirs=None):
    global fails
    try:
        code, out, err = run(src, base_dir, lib_dirs)
    except Exception as e:  # noqa: BLE001
        fails += 1
        print(f"FAIL {name}: исключение {e}")
        return
    if code != 0 or out != expected:
        fails += 1
        print(f"FAIL {name}: код={code} вывод={out!r} ожидалось={expected!r} {err.strip()}")


def bad(name, src, fragment, base_dir=None, lib_dirs=None):
    global fails
    try:
        slog.compile_source(src, base_dir, lib_dirs)
    except slog.SlogError as e:
        if fragment not in str(e):
            fails += 1
            print(f"FAIL {name}: ошибка {e!s} не содержит {fragment!r}")
        return
    fails += 1
    print(f"FAIL {name}: ошибки не было, а ждали {fragment!r}")


def tree(files):
    """Временная папка с файлами {путь: текст}."""
    d = tempfile.mkdtemp()
    for rel, text in files.items():
        p = os.path.join(d, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w", encoding="utf-8") as f:
            f.write(text)
    return d


# ================= модули
d = tree({"m.sl": "функция удвоить(х):\n    вернуть х * 2\n"})
ok("подключить и вызвать", 'подключить "m"\nпечать(удвоить(21))\n', "42\n", d, [])
ok("с расширением", 'подключить "m.sl"\nпечать(удвоить(4))\n', "8\n", d, [])

d = tree({"m.sl": "функция ф():\n    вернуть 1\n"})
ok("повторное подключение", 'подключить "m"\nподключить "m"\nпечать(ф())\n', "1\n", d, [])

d = tree({"a.sl": 'подключить "b"\nфункция фа():\n    вернуть б1() + 1\n',
          "b.sl": "функция б1():\n    вернуть 10\n"})
ok("цепочка подключений", 'подключить "a"\nпечать(фа())\n', "11\n", d, [])

d = tree({"a.sl": 'подключить "b"\nфункция фа():\n    вернуть 1\n',
          "b.sl": 'подключить "a"\nфункция фб():\n    вернуть 2\n'})
ok("подключения по кругу", 'подключить "a"\nпечать(фа() + фб())\n', "3\n", d, [])

d = tree({"sub/a.sl": 'подключить "b"\nфункция фа():\n    вернуть фб()\n',
          "sub/b.sl": "функция фб():\n    вернуть 7\n"})
ok("путь от подключающего файла", 'подключить "sub/a"\nпечать(фа())\n', "7\n", d, [])

lib = tree({"lib1.sl": "функция из_библиотеки():\n    вернуть 5\n"})
d = tree({})
ok("поиск в библиотеке", 'подключить "lib1"\nпечать(из_библиотеки())\n', "5\n", d, [lib])

# файл рядом с программой с тем же именем не подменяет библиотеку
d = tree({"lib1.sl": "функция из_библиотеки():\n    вернуть 111\n"})
ok("библиотека важнее файла рядом", 'подключить "lib1"\nпечать(из_библиотеки())\n', "5\n", d, [lib])
d = tree({"свой.sl": "функция своя():\n    вернуть 3\n"})
ok("свой модуль рядом, если в библиотеке такого нет", 'подключить "свой"\nпечать(своя())\n', "3\n", d, [lib])

d = tree({"m.sl": 'печать("2")\n'})
ok("команды модуля в месте подключения", 'печать("1")\nподключить "m"\nпечать("3")\n', "1\n2\n3\n", d, [])

d = tree({"m.sl": "счёт = 5\nфункция ф():\n    вернуть счёт\n"})
ok("общие переменные", 'подключить "m"\nсчёт += 1\nпечать(ф())\n', "6\n", d, [])

# ================= выбрасывание лишних функций
d = tree({"m.sl": "функция нужная():\n    вернуть 1\nфункция плохая():\n    вернуть нет_такой\n"})
ok("лишняя функция с ошибкой не мешает", 'подключить "m"\nпечать(нужная())\n', "1\n", d, [])
out = slog.compile_source('подключить "m"\nпечать(нужная())\n', d, [])
if "плохая" in out or "функция нужная" not in out:
    fails += 1
    print("FAIL лишняя функция попала в программу")

d = tree({"m.sl": "функция первая():\n    вернуть вторая()\nфункция вторая():\n    вернуть 9\nфункция лишняя():\n    вернуть 0\n"})
ok("функция нужна через другую", 'подключить "m"\nпечать(первая())\n', "9\n", d, [])
out = slog.compile_source('подключить "m"\nпечать(первая())\n', d, [])
if "лишняя" in out or "функция вторая" not in out:
    fails += 1
    print("FAIL цепочка вызовов в библиотеке обработана неверно")

d = tree({"m.sl": "функция ф():\n    вернуть 1\n"})
bad("своя лишняя функция проверяется", 'подключить "m"\nфункция моя():\n    вернуть нет_такой\nпечать(ф())\n', "нигде не задана", d, [])

# ================= ошибки
d = tree({})
bad("нет модуля", 'подключить "нет"\n', "не найден", d, [])
bad("подключить внутри блока", 'если истина:\n    подключить "m"\n', "только на верхнем уровне", d, [])
bad("подключить без имени", "подключить 5\n", "имя модуля в кавычках", d, [])

d = tree({"mod.sl": "функция ф():\n    вернуть нет_такой\n"})
bad("ошибка в модуле называет файл", 'подключить "mod"\nпечать(ф())\n', "mod.sl, строка 2", d, [])

d = tree({"m.sl": "функция ф():\n    вернуть 1\n"})
bad("одинаковые функции в модуле и в программе", 'подключить "m"\nфункция ф():\n    вернуть 2\nпечать(ф())\n', "уже определена", d, [])

d = tree({"a.sl": "функция ф():\n    вернуть 1\n", "b.sl": "функция ф():\n    вернуть 2\n"})
bad("одинаковые функции в двух модулях", 'подключить "a"\nподключить "b"\nпечать(ф())\n', "уже определена", d, [])

d = tree({"m.sl": "х = 1\nх = \"а\"\n"})
bad("ошибка типов в модуле", 'подключить "m"\n', "m.sl, строка 2", d, [])

# ================= библиотека строк
S = 'подключить "stroki"\n'
ok("начинается_с", S + 'печать(начинается_с("привет", "при"), начинается_с("привет", "рив"), начинается_с("а", "аб"), начинается_с("а", ""))\n', "1 0 0 1\n")
ok("заканчивается_на", S + 'печать(заканчивается_на("привет", "вет"), заканчивается_на("привет", "при"), заканчивается_на("а", "аб"))\n', "1 0 0\n")
ok("найти", S + 'печать(найти("привет, мир", "мир"), найти("привет", "xyz"), найти("аб", ""), найти("", "а"), найти("абв", "абвг"), найти("абвабв", "в"))\n', "8 -1 0 -1 -1 2\n")
ok("содержит", S + 'печать(содержит("привет", "ив"), содержит("привет", "яя"))\n', "1 0\n")
ok("обрезать", S + 'печать("[" + обрезать("   привет  мир   ") + "]", "[" + обрезать("   ") + "]", "[" + обрезать("") + "]", "[" + обрезать("а") + "]")\n', "[привет  мир] [] [] [а]\n")
ok("число_слов", S + 'печать(число_слов("  а бв   гд "), число_слов(""), число_слов("   "), число_слов("раз"))\n', "3 0 0 1\n")
ok("слова", S + """
п = слова("  ls  -l   /home ")
печать(длина(п))
для с в п:
    печать("<" + строкой(с) + ">")
печать(длина(слова("")), длина(слова("один")))
""", "3\n<ls>\n<-l>\n</home>\n0 1\n")
ok("соединить", S + 'печать(соединить(слова("а бв гд"), ", "), "|", соединить(["один"], "+"), "|", соединить(список(0), "-"), "|")\n', "а, бв, гд | один |  |\n")
ok("повторить", S + 'печать("[" + повторить("аб", 3) + "]", "[" + повторить("х", 0) + "]", "[" + повторить("", 5) + "]", "[" + повторить("а", -2) + "]")\n', "[абабаб] [] [] []\n")
ok("обратить", S + 'печать(обратить("привет"), обратить(""), обратить("а"))\n', "тевирп  а\n")
ok("в_верхний", S + 'печать(в_верхний("Привет, ёж abc 123"))\n', "ПРИВЕТ, ЁЖ ABC 123\n")
ok("в_нижний", S + 'печать(в_нижний("ПРИВЕТ, ЁЖ ABC 123"))\n', "привет, ёж abc 123\n")
ok("разбор команды", S + """
команда = "  копировать   а.txt  б.txt "
п = слова(обрезать(команда))
если строкой(п[0]) == "копировать":
    печать("из", строкой(п[1]), "в", строкой(п[2]))
""", "из а.txt в б.txt\n")

# ================= библиотека списков
L = 'подключить "spiski"\n'
ok("сумма и крайние", L + 'а = [3, 9, 2, 7]\nпечать(сумма(а), наибольшее(а), наименьшее(а))\n', "21 9 2\n")
ok("содержит_число", L + 'а = [3, 9, 2]\nпечать(содержит_число(а, 9), содержит_число(а, 5))\n', "1 0\n")
ok("копия независима", L + 'а = [1, 2, 3]\nб = копия(а)\nб[0] = 99\nпечать(а[0], б[0], длина(б))\n', "1 99 3\n")
ok("перевернуть", L + 'а = [1, 2, 3, 4, 5]\nперевернуть(а)\nпечать(а[0], а[1], а[2], а[3], а[4])\n', "5 4 3 2 1\n")
ok("перевернуть чётный", L + 'а = [1, 2, 3, 4]\nперевернуть(а)\nпечать(а[0], а[1], а[2], а[3])\n', "4 3 2 1\n")
ok("сортировать", L + 'а = [5, 3, 9, 1, 7, 8, 2, 3]\nсортировать(а)\nдля х в а:\n    печать(х)\n', "1\n2\n3\n3\n5\n7\n8\n9\n")
ok("сортировать пустой и один", L + 'сортировать([])\nа = [4]\nсортировать(а)\nпечать(а[0])\n', "4\n")
ok("сортировать отрицательные", L + 'а = [0, -5, 3, -1]\nсортировать(а)\nпечать(а[0], а[1], а[2], а[3])\n', "-5 -1 0 3\n")

# обе библиотеки вместе
ok("обе библиотеки", S + L + """
п = слова("10 20 30 5")
итог = 0
для с в п:
    итог += число(строкой(с))
печать(итог, длина(п))
""", "65 4\n")

if fails == 0:
    print("SLOG5 TESTS PASS")
else:
    print(f"SLOG5 TESTS FAIL: {fails}")
sys.exit(1 if fails else 0)