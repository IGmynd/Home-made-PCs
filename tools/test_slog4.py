#!/usr/bin/env python3
"""Тесты ввода «Слога»: ввод_строка() читает строку с консоли (UTF-8) и кладёт её как строку.
Запуск: test_slog4.py путь/к/host"""
import os
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ptasm  # noqa: E402
import slog   # noqa: E402

HOST = sys.argv[1]
fails = 0


def run(src, stdin=b""):
    img = ptasm.assemble(slog.compile_source(src))
    with tempfile.NamedTemporaryFile(suffix=".ptb", delete=False) as f:
        f.write(img)
        path = f.name
    try:
        r = subprocess.run([HOST, path], input=stdin, capture_output=True, timeout=20)
    finally:
        os.unlink(path)
    return r.returncode, r.stdout.decode("utf-8"), r.stderr.decode("utf-8")


def ok(name, src, stdin, expected):
    global fails
    try:
        code, out, err = run(src, stdin)
    except Exception as e:  # noqa: BLE001
        fails += 1
        print(f"FAIL {name}: исключение {e}")
        return
    if code != 0 or out != expected:
        fails += 1
        print(f"FAIL {name}: код={code} вывод={out!r} ожидалось={expected!r} {err.strip()}")


def bad(name, src, fragment):
    global fails
    try:
        slog.compile_source(src)
    except slog.SlogError as e:
        if fragment not in str(e):
            fails += 1
            print(f"FAIL {name}: ошибка {e!s} не содержит {fragment!r}")
        return
    fails += 1
    print(f"FAIL {name}: ошибки не было, а ждали {fragment!r}")


# ---------------- ввод строки
ok("эхо", "печать(ввод_строка())\n", "привет\n".encode(), "привет\n")
ok("две строки", "а = ввод_строка()\nб = ввод_строка()\nпечать(б + а)\n", "а\nб\n".encode(), "ба\n")
ok("пустая строка", "печать(длина(ввод_строка()))\n", b"\n", "0\n")
ok("конец ввода", "печать(длина(ввод_строка()))\n", b"", "0\n")
ok("конец ввода без перевода строки", "печать(ввод_строка())\n", "хвост".encode(), "хвост\n")
ok("перевод строки CRLF", "печать(длина(ввод_строка()))\n", "аб\r\n".encode(), "2\n")
ok("после конца ввода", "а = ввод_строка()\nб = ввод_строка()\nпечать(длина(а), длина(б))\n", b"x\n", "1 0\n")
ok("пробелы сохраняются", 'печать("[" + ввод_строка() + "]")\n', "  а б  \n".encode(), "[  а б  ]\n")

# ---------------- UTF-8
ok("длина в буквах", "печать(длина(ввод_строка()))\n", "Игмунд\n".encode(), "6\n")
ok("коды букв", "с = ввод_строка()\nпечать(с[0], с[1])\n", "яб\n".encode(), "1103 1073\n")
ok("4-байтный символ", "с = ввод_строка()\nпечать(длина(с), с[3])\n", "ёж 😀\n".encode(), "4 128512\n")
ok("евро", "печать(ввод_строка())\n", "10 €\n".encode(), "10 €\n")
ok("испорченный UTF-8", "с = ввод_строка()\nпечать(длина(с), с[0])\n", b"\xff\xfe\n", "2 65533\n")
ok("оборванная буква", "с = ввод_строка()\nпечать(длина(с), с[1])\n", b"a\xd1\n", "2 65533\n")
ok("очень длинная строка", "печать(длина(ввод_строка()))\n", b"a" * 5000 + b"\n", "4096\n")

# ---------------- ввод вместе с остальным языком
ok("число из ввода", "печать(число(ввод_строка()) * 2)\n", b"42\n", "84\n")
ok("диалог", """
печать("Как вас зовут?")
имя = ввод_строка()
печать("Привет, " + имя + "!")
печать("букв в имени:", длина(имя))
""", "Игмунд\n".encode(), "Как вас зовут?\nПривет, Игмунд!\nбукв в имени: 6\n")
ok("сумма до пустой строки", """
сумма = 0
пока истина:
    с = ввод_строка()
    если длина(с) == 0:
        прервать
    сумма += число(с)
печать(сумма)
""", "10\n20\n30\n\nпосле\n".encode(), "60\n")
ok("сравнение ввода", """
с = ввод_строка()
если с == "да":
    печать("согласие")
иначе:
    печать("отказ")
""", "да\n".encode(), "согласие\n")
ok("ввод в функции", """
функция спросить():
    вернуть ввод_строка()
печать(спросить() + спросить())
""", "аб\nвг\n".encode(), "абвг\n")
ok("обратить ввод", """
функция обратить(с):
    р = ""
    для к в диапазон(длина(с)):
        р = из_кода(с[к]) + р
    вернуть р
печать(обратить(ввод_строка()))
""", "привет\n".encode(), "тевирп\n")
ok("построчное эхо до конца", """
пока истина:
    с = ввод_строка()
    если длина(с) == 0:
        прервать
    печать("> " + с)
""", "один\nдва\nтри\n".encode(), "> один\n> два\n> три\n")
ok("ввод_символ и ввод_строка вместе", """
печать(ввод_символ())
печать(ввод_строка())
""", b"abc\n", "97\nbc\n")

# ---------------- типы
bad("строка плюс число из ввода", "печать(ввод_строка() + 1)\n", "нельзя сложить строку и число")
bad("ввод в числовую переменную", "х = 5\nх = ввод_строка()\n", "и число, и строку")
bad("ввод с аргументом", "печать(ввод_строка(1))\n", "принимает аргументов")
bad("ввод как условие", "если ввод_строка():\n    пропуск\n", "условие: ожидалось число")

if fails == 0:
    print("SLOG4 TESTS PASS")
else:
    print(f"SLOG4 TESTS FAIL: {fails}")
sys.exit(1 if fails else 0)